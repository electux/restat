#pragma once

#include <string>

namespace Electux::App::Com {
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    /// @class IBle
    /// @brief Interface for BLE communication configuration parameters.
    ////////////////////////////////////////////////////////////////////////////////////////////////////
    class IBle {
      public:
        virtual ~IBle() = default;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Sets the target MAC address or name for the BLE device.
        /// @param address The device address or name.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void setBleAddress(const std::string &address) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Sets the target Service UUID.
        /// @param uuid The Service UUID.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void setServiceUuid(const std::string &uuid) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Sets the target RX Characteristic UUID.
        /// @param uuid The RX Characteristic UUID.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void setRxUuid(const std::string &uuid) = 0;

        ////////////////////////////////////////////////////////////////////////////////////////////////
        /// @brief Sets the target TX Characteristic UUID.
        /// @param uuid The TX Characteristic UUID.
        ////////////////////////////////////////////////////////////////////////////////////////////////
        virtual void setTxUuid(const std::string &uuid) = 0;
    };
} // namespace Electux::App::Com
